#!/usr/bin/env python3
"""Extract the gptoss_ext source tree from gptoss_ext/diff.patch into a build directory.

The patch is a set of "new file" additions (plus two unrelated serve/ edits at the end).
Binary files (the tiny safetensors fixtures) are not carried in the patch: they are
regenerated by tools/tiny_gptoss.py.
"""
import os
import re
import sys


def main(patch_path, out_dir):
    with open(patch_path, "r", encoding="utf-8", errors="replace") as fh:
        lines = fh.read().split("\n")

    files = {}
    i = 0
    cur = None
    mode = None
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("diff --git "):
            m = re.match(r"^diff --git a/(\S+) b/(\S+)$", ln)
            cur = m.group(2) if m else None
            mode = None
            i += 1
            continue
        if cur is None:
            i += 1
            continue
        if ln.startswith("new file mode"):
            mode = "new"
            i += 1
            continue
        if ln.startswith("Binary files"):
            files[cur] = None  # not extractable
            cur = None
            i += 1
            continue
        if ln.startswith("@@"):
            i += 1
            body = []
            while i < len(lines):
                b = lines[i]
                if b.startswith("@@") or b.startswith("diff --git"):
                    break
                if b.startswith("+++") or b.startswith("---"):
                    i += 1
                    continue
                if b.startswith("+"):
                    body.append(b[1:])
                elif b.startswith("-") or b.startswith(" "):
                    body.append(b[1:])
                i += 1
            prev = files.get(cur)
            if prev is None:
                files[cur] = "\n".join(body) + "\n"
            else:
                files[cur] = prev + "\n".join(body) + "\n"
            continue
        i += 1

    written = []
    for path, content in sorted(files.items()):
        if content is None:
            print("SKIP binary:", path)
            continue
        if not path.startswith("gptoss_ext/"):
            print("SKIP outside:", path)
            continue
        rel = path[len("gptoss_ext/"):]
        dst = os.path.join(out_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "w", encoding="utf-8") as out:
            out.write(content)
        written.append(rel)
    print("extracted %d files into %s" % (len(written), out_dir))


if __name__ == "__main__":
    patch = sys.argv[1] if len(sys.argv) > 1 else "gptoss_ext/diff.patch"
    out = sys.argv[2] if len(sys.argv) > 2 else "/var/tmp/gptoss-ext-build"
    main(patch, out)
